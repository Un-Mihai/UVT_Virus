// Regenerates src/lib/api/schema.d.ts from the running FastAPI app's OpenAPI document.
// Run after changing any API route or model: `npm run gen:api` (API must be up).
import { writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";
import ts from "typescript";

const apiUrl = process.env.API_URL ?? "http://localhost:8000";
const BLOB = ts.factory.createTypeReferenceNode(
  ts.factory.createIdentifier("Blob"),
);
const ast = await openapiTS(new URL("/openapi.json", apiUrl), {
  // Uploaded files (FastAPI's UploadFile) are Blobs in the browser, not strings.
  transform(schemaObject) {
    const binary =
      schemaObject.format === "binary" ||
      schemaObject.contentMediaType === "application/octet-stream";
    return binary ? BLOB : undefined;
  },
});
const header =
  "// Generated by `npm run gen:api` from the FastAPI OpenAPI schema. Do not edit.\n\n";
await writeFile(
  new URL("../src/lib/api/schema.d.ts", import.meta.url),
  header + astToString(ast),
);
console.log(`Wrote src/lib/api/schema.d.ts from ${apiUrl}/openapi.json`);
